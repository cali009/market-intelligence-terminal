"""
Phase 34.5 -- Annual Automated Order System Attestation
US + Canada Market Intelligence Platform

CIRO / UMIR Policy 7.1 Part 8 requires that an automated order system be tested before use
and **at least annually**, with a written record; that the Participant be able to override
or disable it immediately; and that the Participant remain responsible for its orders
including "runaway algo" behaviour.

This module produces that written record. It is a genuine compliance artifact rather than
theatre: the attestation is generated by actually running the control-coverage suite and
recording what passed, what failed, and which code version was tested. An attestation that
merely asserted "we tested it" would not be a record of anything.

What is attested, and what is not:

  - ATTESTED: every pre-trade control C1..C12 is registered and exercised by a test; the
    routing gates (Canadian firewall, license, capability) are exercised; the state machine
    is exercised; the kill switch can actually halt routing; the execution test suites pass.
  - NOT ATTESTED: profitability, fill-quality realism, or suitability of any signal. This
    platform is unregistered impersonal research and makes no such claim.
"""

import hashlib
import json
import os
import subprocess
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from config.settings import BASE_DIR, DATA_DIR
from src.data.db import Database, db as _default_db
from src.execution.risk_governor import CONTROL_REGISTRY
from src.execution.state_machine import LEGAL_TRANSITIONS

ATTESTATION_DIR = DATA_DIR / "attestations"
ATTESTATION_VALIDITY_DAYS = 365

# The execution suites that constitute the control-coverage evidence.
EXECUTION_TEST_SUITES = [
    "tests/test_execution_order_lifecycle.py",
    "tests/test_execution_risk_governor.py",
    "tests/test_execution_internal_simulator.py",
    "tests/test_execution_router.py",
    "tests/test_execution_telemetry.py",
    # Included deliberately: an attestation whose evidence set omits its own tests would
    # understate coverage. See REENTRANCY_GUARD_ENV -- the suite is written so that running
    # it inside an attestation does not start another attestation.
    "tests/test_execution_aos_feed.py",
]

# Set in the environment of the pytest subprocesses. The attestation suite checks for it and
# skips the one test that would otherwise invoke run_attestation(run_tests=True) again,
# which would recurse until the process died. A guard rather than an omission, so the
# evidence set stays complete.
REENTRANCY_GUARD_ENV = "AOS_ATTESTATION_IN_PROGRESS"


@dataclass
class AosAttestation:
    """One annual testing record."""
    year: int
    attested_at: str
    code_version: str
    controls_registered: int = 0
    controls_with_tests: int = 0
    controls_without_tests: List[str] = field(default_factory=list)
    routing_gates_checked: int = 0
    state_machine_edges: int = 0
    kill_switch_verified: bool = False
    tests_passed: int = 0
    tests_failed: int = 0
    suites_run: int = 0
    passed: bool = False
    artifact_path: str = ""
    scope_note: str = ""

    @property
    def days_until_expiry(self) -> int:
        """
        Days remaining before Policy 7.1 Part 8 requires re-testing.

        Returns -1 when the attestation date cannot be parsed. A record whose date is
        unreadable cannot be shown to be current, so it must read as expired rather than
        silently valid -- failing closed is the only safe answer for a compliance artifact.
        """
        try:
            attested = datetime.fromisoformat(self.attested_at)
        except ValueError:
            return -1
        elapsed = (datetime.now(timezone.utc) - attested).days
        return ATTESTATION_VALIDITY_DAYS - elapsed

    @property
    def expired(self) -> bool:
        return self.days_until_expiry < 0

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["days_until_expiry"] = self.days_until_expiry
        d["expired"] = self.expired
        return d


