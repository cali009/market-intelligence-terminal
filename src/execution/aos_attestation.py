# Attestation
# --------------------------------------------------------------------------------------

def run_attestation(db: Optional[Database] = None, year: Optional[int] = None,
                    run_tests: bool = True) -> AosAttestation:
    """
    Runs the control-coverage suite, writes the JSON artifact, and records the row.

    `passed` is True only when every registered control has coverage, the kill switch was
    verified live, and no test failed. A partial result is recorded as a failed
    attestation rather than silently rounded up.
    """
    conn = db or _default_db
    year = year or datetime.now(timezone.utc).year
    now = datetime.now(timezone.utc)

    coverage = _controls_with_test_coverage()
    without = sorted(cid for cid, ok in coverage.items() if not ok)

    ks_ok = _verify_kill_switch(conn)
    tests = _run_test_suites() if run_tests else {"passed": 0, "failed": 0, "suites": 0}

    att = AosAttestation(
        year=year,
        attested_at=now.isoformat(),
        code_version=_git_revision(),
        controls_registered=len(CONTROL_REGISTRY),
        controls_with_tests=sum(1 for ok in coverage.values() if ok),
        controls_without_tests=without,
        routing_gates_checked=5,   # firewall, license, capability, configured, market
        state_machine_edges=sum(len(v) for v in LEGAL_TRANSITIONS.values()),
        kill_switch_verified=ks_ok,
        tests_passed=tests["passed"],
        tests_failed=tests["failed"],
        suites_run=tests["suites"],
        scope_note=(
            "Attests pre-trade control coverage, routing gates, state-machine integrity and "
            "kill-switch operation only. Does not attest profitability, fill-quality "
            "realism, or the suitability of any signal. Unregistered impersonal research; "
            "no external broker adapter ships and no order routes to a live venue."
        ),
    )
    att.passed = (not without) and ks_ok and tests["failed"] == 0 and tests["suites"] > 0

    ATTESTATION_DIR.mkdir(parents=True, exist_ok=True)
    artifact = ATTESTATION_DIR / f"aos_{year}.json"
    with open(artifact, "w", encoding="utf-8") as f:
        json.dump(att.to_dict(), f, indent=2)
    att.artifact_path = str(artifact)

    _ensure_table(conn)
    conn.execute_write(
        """
        INSERT INTO aos_attestation
            (year, attested_at, code_version, controls_registered, controls_with_tests,
             controls_without_tests, routing_gates_checked, state_machine_edges,
             kill_switch_verified, tests_passed, tests_failed, suites_run, passed,
             artifact_path, scope_note)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ON CONFLICT(year) DO UPDATE SET
            attested_at=excluded.attested_at,
            code_version=excluded.code_version,
            controls_registered=excluded.controls_registered,
            controls_with_tests=excluded.controls_with_tests,
            controls_without_tests=excluded.controls_without_tests,
            routing_gates_checked=excluded.routing_gates_checked,
            state_machine_edges=excluded.state_machine_edges,
            kill_switch_verified=excluded.kill_switch_verified,
            tests_passed=excluded.tests_passed,
            tests_failed=excluded.tests_failed,
            suites_run=excluded.suites_run,
            passed=excluded.passed,
            artifact_path=excluded.artifact_path,
            scope_note=excluded.scope_note;
        """,
        (att.year, att.attested_at, att.code_version, att.controls_registered,
         att.controls_with_tests, json.dumps(without), att.routing_gates_checked,
         att.state_machine_edges, 1 if att.kill_switch_verified else 0,
         att.tests_passed, att.tests_failed, att.suites_run, 1 if att.passed else 0,
         att.artifact_path, att.scope_note),
    )
    return att


def _ensure_table(conn: Database) -> None:
    conn.execute_write(
        """
        CREATE TABLE IF NOT EXISTS aos_attestation (
            year                   INTEGER PRIMARY KEY,
            attested_at            TEXT    NOT NULL,
            code_version           TEXT    NOT NULL,
            controls_registered    INTEGER NOT NULL,
            controls_with_tests    INTEGER NOT NULL,
            controls_without_tests TEXT,
            routing_gates_checked  INTEGER NOT NULL,
            state_machine_edges    INTEGER NOT NULL,
            kill_switch_verified   INTEGER NOT NULL,
            tests_passed           INTEGER NOT NULL,
            tests_failed           INTEGER NOT NULL,
            suites_run             INTEGER NOT NULL,
            passed                 INTEGER NOT NULL,
            artifact_path          TEXT,
            scope_note             TEXT
        );
        """
    )


def latest_attestation(db: Optional[Database] = None) -> Optional[AosAttestation]:
    """Most recent record, or None if the system has never been attested."""
    conn = db or _default_db
    try:
        _ensure_table(conn)
        rows = conn.execute_query(
            "SELECT * FROM aos_attestation ORDER BY year DESC, attested_at DESC LIMIT 1;"
        )
    except Exception:
        return None
    if not rows:
        return None
    r = rows[0]
    try:
        without = json.loads(r["controls_without_tests"] or "[]")
    except (TypeError, ValueError):
        without = []
    att = AosAttestation(
        year=int(r["year"]), attested_at=r["attested_at"], code_version=r["code_version"],
        controls_registered=int(r["controls_registered"]),
        controls_with_tests=int(r["controls_with_tests"]),
        controls_without_tests=without,
        routing_gates_checked=int(r["routing_gates_checked"]),
        state_machine_edges=int(r["state_machine_edges"]),
        kill_switch_verified=bool(r["kill_switch_verified"]),
        tests_passed=int(r["tests_passed"]), tests_failed=int(r["tests_failed"]),
        suites_run=int(r["suites_run"]), passed=bool(r["passed"]),
        artifact_path=r["artifact_path"] or "", scope_note=r["scope_note"] or "",
    )
    return att


def artifact_digest(path: Optional[str] = None) -> str:
    """SHA-256 of the attestation artifact, so the record can be tied to its evidence."""
    if not path or not Path(path).exists():
        return ""
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


