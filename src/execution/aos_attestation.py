# Evidence collection
# --------------------------------------------------------------------------------------

def _git_revision() -> str:
    """The commit the suite was run against. Unavailable is recorded, not guessed."""
    try:
        out = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=str(BASE_DIR),
            capture_output=True, text=True, timeout=15,
        )
        if out.returncode == 0:
            return out.stdout.strip()
    except Exception:
        pass
    return "UNKNOWN"


def _controls_with_test_coverage() -> Dict[str, bool]:
    """
    Checks that each registered control is named in the governor test suite.

    Matching on the control id is a coverage proxy, not a proof of correctness: it verifies
    a test mentions the control, which is necessary but not sufficient. Recorded as such.
    """
    suite = BASE_DIR / "tests" / "test_execution_risk_governor.py"
    text = suite.read_text(encoding="utf-8") if suite.exists() else ""
    # Strip comments so an explanatory comment cannot masquerade as coverage.
    code = "\n".join(line.split("#")[0] for line in text.splitlines())
    return {c.control_id: (f'"{c.control_id}"' in code or f"'{c.control_id}'" in code
                           or f"{c.control_id.lower()}(" in code)
            for c in CONTROL_REGISTRY}


def _verify_kill_switch(db: Database) -> bool:
    """
    Confirms the kill switch can actually halt routing and be reversed. An attestation that
    claimed this without exercising it would be asserting the one control whose failure
    mode is catastrophic.
    """
    from src.execution.order_model import Market, OrderRequest, OrderSide, OrderType, \
        build_client_order_id
    from src.execution.router import KILL_ALL, AdapterRegistry, AdapterRouter, KillSwitch
    from src.execution.adapters.internal_simulator import InternalSimulatorAdapter
    from src.execution.state_machine import ExecutionLedger
    from datetime import date

    ks = KillSwitch(db=db)
    reg = AdapterRegistry()
    reg.register(InternalSimulatorAdapter(ledger=ExecutionLedger(db=db), db=db))
    rt = AdapterRouter(registry=reg, kill_switch=ks)

    req = OrderRequest(
        client_order_id=build_client_order_id("ZZTEST", "BUY", 1, "MARKET", "AOS",
                                              date(2026, 1, 1)),
        symbol="ZZTEST", market=Market.US, side=OrderSide.BUY, quantity=1,
        order_type=OrderType.MARKET, signal_date=date(2026, 1, 1),
    )
    ks.engage(KILL_ALL, reason="AOS attestation self-test")
    try:
        halted = rt.route(req).allowed is False
    finally:
        ks.disengage(KILL_ALL, reason="AOS attestation self-test")
    restored = rt.route(req).allowed is True
    return halted and restored


def _run_test_suites() -> Dict[str, Any]:
    """Runs the execution suites and returns pass/fail counts."""
    passed = failed = suites = 0
    for suite in EXECUTION_TEST_SUITES:
        if not (BASE_DIR / suite).exists():
            continue
        try:
            env = {**os.environ, REENTRANCY_GUARD_ENV: "1"}
            out = subprocess.run(
                ["python3", "-m", "pytest", suite, "-q", "--no-header", "-p", "no:cacheprovider"],
                cwd=str(BASE_DIR), capture_output=True, text=True, timeout=900, env=env,
            )
            tail = out.stdout.strip().splitlines()[-1] if out.stdout.strip() else ""
            suites += 1
            for token in tail.replace(",", " ").split():
                if token.isdigit():
                    n = int(token)
                elif token == "passed":
                    passed += n
                elif token in ("failed", "errors"):
                    failed += n
        except Exception:
            suites += 1
            failed += 1
    return {"passed": passed, "failed": failed, "suites": suites}


