"""
Phase 32 invariants that survive the honesty overhaul.

HONESTY OVERHAUL (Phase 2) deleted tests/test_darkpool_release.py and
tests/test_options_release.py. Both were release audits of a publication surface
that no longer exists: they asserted that dark_pool_liquidity.json and
options_intelligence.json were staged, internally consistent, and rendered in the
terminal UI. Those feeds were generated by np.random.default_rng seeded per
symbol and by a hard-coded tenor table, so "internally consistent" only meant the
random numbers agreed with each other. The feeds, the panels and the exports are
gone.

Three tests in those modules checked real, surviving code rather than the
published artifacts, and they are preserved here unchanged in substance:

  1. ATS share must never reach the sentinel metric surface (Phase 32 decision:
     ATS/dark-pool share is reference display only, excluded from scoring).
  2. Predicates 24 and 25 must be wired into the sentinel engine.
  3. The portfolio orchestrator must consume the commercial build and must never
     request research-only short metrics.

Everything else those modules asserted was about deleted files and deleted HTML.
"""

import inspect
from pathlib import Path


def test_sentinel_metric_surface_carries_no_ats_field():
    """The engine's sentinel surface must not expose any ATS field."""
    from src.engine.dark_pool_liquidity import dark_pool_liquidity_engine

    feed = dark_pool_liquidity_engine.evaluate_dark_pool_liquidity(
        include_research_only_short_metrics=True, force_refresh=True
    )
    surface = dark_pool_liquidity_engine.compute_sentinel_metrics(feed)
    assert surface["per_symbol"], "sentinel surface is empty"
    for sym, m in surface["per_symbol"].items():
        assert [k for k in m if "ats" in k.lower()] == [], f"{sym}: ATS leaked into sentinel surface"


def test_predicates_24_and_25_are_wired_into_sentinel_engine():
    """The sentinel must expose dark_pool_metrics and both Phase 32 predicates."""
    from src.engine.quant_intel_sentinel import quant_intel_sentinel

    sig = inspect.signature(quant_intel_sentinel.evaluate_portfolio_level_sentinels)
    assert "dark_pool_metrics" in sig.parameters

    source = inspect.getsource(quant_intel_sentinel.evaluate_portfolio_level_sentinels)
    for token in (
        "DARK_POOL_STEALTH_DISTRIBUTION",
        "SHORT_VOLUME_SQUEEZE_SPIKE",
        "SCRUTINIZE_BUY_SIGNALS",
        "FLAG_SHORT_COVERING_CASCADE",
    ):
        assert token in source, f"{token} not wired"


def test_orchestrator_uses_commercial_gated_build():
    """The orchestrator must consume the commercial build (no research-only flag)."""
    src = (Path("src") / "engine" / "portfolio_orchestrator.py").read_text(encoding="utf-8")
    assert "from src.engine.dark_pool_liquidity import dark_pool_liquidity_engine" in src
    assert "dark_pool_liquidity_engine.evaluate_dark_pool_liquidity()" in src
    assert "dark_pool_metrics=dark_pool_liquidity_engine.compute_sentinel_metrics" in src
    # Must NOT request research-only short metrics in the commercial orchestration path.
    assert "include_research_only_short_metrics=True" not in src


def test_retired_fabricated_feeds_are_no_longer_written_or_published():
    """The three fabricated feeds must be absent from feeds, dist and public/api.

    This is the regression guard for the Phase 2 deletion: if any of these files
    reappears, something has started publishing invented numbers again.
    """
    for name in ("microstructure_snapshot", "dark_pool_liquidity", "options_intelligence"):
        for d in ("data/feeds", "data/dist", "public/api"):
            p = Path(d) / f"{name}.json"
            assert not p.exists(), f"{p} reappeared — this feed was retired as fabricated"

    # And the build script must not stage them.
    build = (Path("scripts") / "build_firebase_public.py").read_text(encoding="utf-8")
    for name in ("microstructure_snapshot", "dark_pool_liquidity", "options_intelligence"):
        assert f'"{name}.json"' not in build, f"{name}.json is staged for publishing again"
